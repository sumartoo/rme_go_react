-- Master Data > MCU: the MCU examination groups (General, Fisik, Spirometri,
-- Darah, ...). Same columns, types and primary key as refmastermcu in the
-- legacy "lab" database. Data is loaded with scripts/import-lab-master-mcu.sh.
-- lab has no unique constraint on the code, so neither does this table.
CREATE TABLE IF NOT EXISTS refmastermcu (
    id            integer GENERATED BY DEFAULT AS IDENTITY,
    mcumastercode varchar(10),
    mcumastername varchar(30),
    CONSTRAINT pk_refmastermcu PRIMARY KEY (id)
);
