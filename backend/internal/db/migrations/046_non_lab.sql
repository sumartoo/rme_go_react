-- Master Data > Non Lab: services sold with an MCU that are not lab
-- examinations (Sameday, Review MCU, Home Service, ...), with a price. Same
-- columns, types and primary key as refnonlab in the legacy "lab" database.
-- Data is loaded with scripts/import-lab-non-lab.sh. Soft-deleted rows
-- (isdeleted) are hidden.
CREATE TABLE IF NOT EXISTS refnonlab (
    id           integer GENERATED BY DEFAULT AS IDENTITY,
    name         varchar(100),
    price        double precision,
    isdeleted    boolean,
    createddate  timestamp(3) without time zone,
    createby     varchar(30),
    modifieddate timestamp(3) without time zone,
    modifiedby   varchar(30),
    deleteddate  timestamp(3) without time zone,
    deletedby    varchar(30),
    CONSTRAINT refnonlab_pkey PRIMARY KEY (id)
);
