-- MCU > the 16 result forms (Pemeriksaan Fisik, Riwayat Medis, ..., USG).
--
-- 1. The examination catalogue of the legacy "lab" database, same columns:
--    mcu_group (A Identitas, B Riwayat Penyakit, G Pemeriksaan Fisik, ...)
--    -> mcu_type (a section, e.g. 06 Mata) -> mcu_items (e.g. 061 Persepsi
--    warna) -> phisic_resulted_type / resulted_type (the answers an item offers,
--    entry_type radio or text). An item is keyed by check_up_type + item_id
--    (item ids repeat across types). Loaded with scripts/import-lab-mcu.sh.
-- 2. The MCU registrations (trxmcuheader) and the examinations ordered with
--    them (trxmcudetail), same columns as lab, also from that script.
-- 3. The results, new: one row per registration and form (status, conclusion)
--    and its answers as key/value pairs, so every form shares one layout. No
--    foreign key to trxmcuheader: its re-import (--replace) would cascade and
--    wipe the results, as for the other re-imported tables.
CREATE TABLE IF NOT EXISTS mcu_group (
    group_type   char(1) PRIMARY KEY,
    group_name   varchar(30),
    default_flag char(1),
    detail_flag  char(1),
    sort_id      integer,
    input_date   timestamp,
    input_by     varchar(30)
);
CREATE TABLE IF NOT EXISTS mcu_type (
    check_up_type char(2) PRIMARY KEY,
    group_type    char(1),
    name          varchar(30),
    confirm_date  timestamp,
    expired_date  date
);
CREATE TABLE IF NOT EXISTS mcu_items (
    check_up_type    char(2),
    item_id          char(3),
    item_description varchar(40),
    confirm_date     timestamp,
    expired_date     date,
    PRIMARY KEY (check_up_type, item_id)
);
CREATE TABLE IF NOT EXISTS resulted_type (
    resulted_type char(2) PRIMARY KEY,
    resulted_name varchar(100),
    entry_type    varchar(20),
    group_type    char(1),
    confirm_date  timestamp
);
CREATE TABLE IF NOT EXISTS phisic_resulted_type (
    resulted_type char(2),
    check_up_type char(2),
    item_id       char(3),
    sort_id       char(3)
);
CREATE INDEX IF NOT EXISTS phisic_resulted_type_item_idx ON phisic_resulted_type (check_up_type, item_id);

--   pasienid    refpasien (MCU patients)
--   status      New, Close or Cancel
CREATE TABLE IF NOT EXISTS trxmcuheader (
    id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pasienid      integer,
    mcudate       timestamp,
    status        varchar(10),
    createddate   timestamp,
    createby      varchar(30),
    modifieddate  timestamp,
    modifiedby    varchar(30),
    deleteddate   timestamp,
    deletedby     varchar(30),
    price         double precision,
    resume        text,
    inviceno      varchar(50),
    invoicedate   timestamp,
    cancelremarks varchar(300),
    canceldate    timestamp,
    cancelby      varchar(50),
    mcukategoriid integer,
    mcuinfoid     integer
);
CREATE INDEX IF NOT EXISTS trxmcuheader_mcudate_idx ON trxmcuheader (mcudate DESC);
CREATE INDEX IF NOT EXISTS trxmcuheader_pasienid_idx ON trxmcuheader (pasienid);

--   labid  reflab: the examination ordered; paketid refpriceheader
CREATE TABLE IF NOT EXISTS trxmcudetail (
    id       integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    headerid integer,
    paketid  integer,
    labid    integer,
    status   varchar(10),
    result   varchar(100),
    price    double precision
);
CREATE INDEX IF NOT EXISTS trxmcudetail_headerid_idx ON trxmcudetail (headerid);

--   form        the form's slug (fisik, riwayat-medis, ..., usg)
--   status      normal, abnormal or '' (not decided)
CREATE TABLE IF NOT EXISTS mcu_hasil_form (
    header_id  integer NOT NULL,
    form       varchar(30) NOT NULL,
    status     varchar(10) NOT NULL DEFAULT '',
    kesimpulan text NOT NULL DEFAULT '',
    updated_by varchar(50) NOT NULL DEFAULT '',
    updated_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (header_id, form)
);

--   item_key  catalogue items: "<check_up_type>.<item_id>"; other forms name
--             their own fields; lists (e.g. job history) are JSON in one value
CREATE TABLE IF NOT EXISTS mcu_hasil_item (
    header_id integer NOT NULL,
    form      varchar(30) NOT NULL,
    item_key  varchar(60) NOT NULL,
    value     text NOT NULL DEFAULT '',
    note      text NOT NULL DEFAULT '',
    PRIMARY KEY (header_id, form, item_key),
    FOREIGN KEY (header_id, form) REFERENCES mcu_hasil_form (header_id, form) ON DELETE CASCADE
);
