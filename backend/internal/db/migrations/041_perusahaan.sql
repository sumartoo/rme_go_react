-- Master Data > Perusahaan: the client companies (refcompany). Same columns,
-- types and primary key as in the legacy "lab" database. Data is loaded with
-- scripts/import-lab-perusahaan.sh. The code identifies a company and is
-- unique in lab (127 rows, 127 codes), so it is unique here too.
CREATE TABLE IF NOT EXISTS refcompany (
    companyid           integer GENERATED BY DEFAULT AS IDENTITY,
    companycode         varchar(10),
    companyname         varchar(255),
    companyaddress      varchar(255),
    companycontacperson varchar(100),
    companymail         varchar(100),
    companyphone        varchar(30),
    companyfax          varchar(30),
    isvat               varchar(2),
    CONSTRAINT pk_refcompany PRIMARY KEY (companyid),
    CONSTRAINT refcompany_companycode_key UNIQUE (companycode)
);
