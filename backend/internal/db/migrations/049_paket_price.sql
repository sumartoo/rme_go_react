-- Setting > Paket Price: MCU packages and prices per company.
--   refcategory     the MCU categories (MCU Kategori 1..3), chosen per package
--   refpriceheader  a package: company (refcompany.companyid), name, Paket Ya/Tidak,
--                   validity dates, price, category, status (isactive 1/0).
--                   isdeleted hides a package (Delete); transactions refer to it
--                   (trxmcudetail.paketid in lab), so rows are never removed.
--   refpricedetail  the lab examinations (reflab.labid) in a package. lab also has
--                   iscek/price/percentage1..3 here, all empty; they are kept.
-- Same columns, types and primary keys as in the legacy "lab" database. Data is
-- loaded with scripts/import-lab-paket-price.sh. References are not enforced,
-- like lab.
CREATE TABLE IF NOT EXISTS refcategory (
    id       integer GENERATED BY DEFAULT AS IDENTITY,
    category varchar(50),
    note     varchar(200),
    CONSTRAINT refcategory_pkey PRIMARY KEY (id)
);

CREATE TABLE IF NOT EXISTS refpriceheader (
    id           integer GENERATED BY DEFAULT AS IDENTITY,
    companyid    integer,
    paketname    varchar(30),
    ispaket      boolean,
    fromdate     timestamp(3) without time zone,
    todate       timestamp(3) without time zone,
    price        double precision,
    isdeleted    boolean,
    createddate  timestamp(3) without time zone,
    createby     varchar(30),
    modifieddate timestamp(3) without time zone,
    modifiedby   varchar(30),
    deleteddate  timestamp(3) without time zone,
    deletedby    varchar(30),
    kategoriid   integer,
    fee          double precision DEFAULT 15,
    isactive     integer DEFAULT 1,
    CONSTRAINT pk_refpriceheader PRIMARY KEY (id)
);

CREATE TABLE IF NOT EXISTS refpricedetail (
    id          integer GENERATED BY DEFAULT AS IDENTITY,
    headerid    integer,
    labid       integer,
    iscek       boolean,
    price       double precision,
    percentage1 double precision,
    percentage2 double precision,
    percentage3 double precision,
    CONSTRAINT pk_refpricedetail PRIMARY KEY (id)
);

CREATE INDEX IF NOT EXISTS refpricedetail_headerid ON refpricedetail (headerid);
