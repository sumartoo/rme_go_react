-- Master Data > Lab Sub Master: the subgroups of lab examinations under a Lab
-- Master (reflabmaster), e.g. KIMIA KLINIK > FAAL HATI. Same columns, types and
-- primary key as reflabsubmaster in the legacy "lab" database. Data is loaded
-- with scripts/import-lab-lab-sub-master.sh. labmasterid points to
-- reflabmaster (not enforced, like lab). Soft-deleted rows (isdeleted) are hidden.
CREATE TABLE IF NOT EXISTS reflabsubmaster (
    labsubmasterid   integer GENERATED BY DEFAULT AS IDENTITY,
    labmasterid      integer,
    labsubmastercode varchar(20),
    labsubmastername varchar(50),
    isdeleted        boolean,
    createddate      timestamp(3) without time zone,
    createby         varchar(30),
    modifieddate     timestamp(3) without time zone,
    modifiedby       varchar(30),
    deleteddate      timestamp(3) without time zone,
    deletedby        varchar(30),
    CONSTRAINT pk_reflabsubmaster PRIMARY KEY (labsubmasterid)
);

CREATE INDEX IF NOT EXISTS reflabsubmaster_labmasterid ON reflabsubmaster (labmasterid);
