-- Setting > Barcode: the layout of the MCU barcode label (margins, row
-- positions, barcode size and position, font size). lab holds one row. Same
-- columns, types and primary key as refsettingbarcode in the legacy "lab"
-- database; "left" and "right" are reserved words, so SQL quotes them. Data is
-- loaded with scripts/import-lab-setting-barcode.sh.
CREATE TABLE IF NOT EXISTS refsettingbarcode (
    id            integer GENERATED BY DEFAULT AS IDENTITY,
    "left"        double precision,
    middle        double precision,
    "right"       double precision,
    row1          double precision,
    row2          double precision,
    row3          double precision,
    row4          double precision,
    row5          double precision,
    row6          double precision,
    barcodewidth  double precision,
    barcodeheight double precision,
    barcodeleft   double precision,
    barcodetop    double precision,
    fontsize      double precision,
    isactive      integer NOT NULL DEFAULT 0,
    CONSTRAINT refsettingbarcode_pkey PRIMARY KEY (id)
);
