-- Stok Farmasi > Stok Adjusment: manual stock corrections per drug and branch.
-- Same columns, types and primary key as trxstokadjus in the legacy "lab"
-- database. Data is loaded with scripts/import-lab-stok-adjusment.sh.
--   tanggal  the adjustment date (midnight, clinic time)
--   byk      quantity, in the drug's selling unit
--   status   1 = Masuk (stock goes up), 0 = Keluar (stock goes down)
--   cabang   refbranch.kode
CREATE TABLE IF NOT EXISTS trxstokadjus (
    id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tanggal     timestamp(3),
    id_obat     integer,
    ket         varchar(60),
    byk         double precision,
    status      integer,
    create_user varchar(20),
    create_date timestamp(3),
    update_user varchar(20),
    update_date timestamp(3),
    cabang      varchar(10)
);

-- Additions: lab has adjustments of drugs that were deleted; they are not imported.
ALTER TABLE trxstokadjus
    ADD CONSTRAINT fk_trxstokadjus_obat   FOREIGN KEY (id_obat) REFERENCES refobat (id) ON DELETE CASCADE,
    ADD CONSTRAINT fk_trxstokadjus_cabang FOREIGN KEY (cabang)  REFERENCES refbranch (kode);
CREATE INDEX IF NOT EXISTS trxstokadjus_cabang_tanggal_idx ON trxstokadjus (cabang, tanggal);
