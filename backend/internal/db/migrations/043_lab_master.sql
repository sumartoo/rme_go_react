-- Master Data > Lab Master: the groups of lab examinations (BIOMOLEKULER,
-- KIMIA KLINIK, DOKTER UMUM, ...). Same columns, types and primary key as
-- reflabmaster in the legacy "lab" database. Data is loaded with
-- scripts/import-lab-lab-master.sh. lab has no unique constraint on the code,
-- so neither does this table. Soft-deleted rows (isdeleted) are hidden.
CREATE TABLE IF NOT EXISTS reflabmaster (
    labmasterid   integer GENERATED BY DEFAULT AS IDENTITY,
    labmastercode varchar(20),
    labmastername varchar(50),
    isdeleted     boolean,
    createddate   timestamp(3) without time zone,
    createby      varchar(30),
    modifieddate  timestamp(3) without time zone,
    modifiedby    varchar(30),
    deleteddate   timestamp(3) without time zone,
    deletedby     varchar(30),
    CONSTRAINT pk_reflabmaster PRIMARY KEY (labmasterid)
);
