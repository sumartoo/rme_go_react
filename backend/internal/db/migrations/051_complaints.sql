-- Customer complaints analysed by AI through the n8n workflow (DeepSeek).
--
--   ai_status        pending    = saved, not sent to n8n yet
--                    processing = sent to n8n, waiting for the analysis
--                    analyzed   = analysis received and validated
--                    failed     = n8n unreachable after all retries, or the
--                                 AI output failed validation (see ai_error)
--   handling_status  open, in_progress, resolved, closed (set by staff)
--   ai_raw           the validated analysis as received, for audit
CREATE TABLE IF NOT EXISTS complaints (
    id               bigint GENERATED BY DEFAULT AS IDENTITY,
    customer_name    varchar(100) NOT NULL,
    customer_contact varchar(100),
    channel          varchar(30)  NOT NULL DEFAULT 'app',
    message          text         NOT NULL,
    category         varchar(50),
    sentiment        varchar(10),
    priority         varchar(10),
    summary          text,
    ai_raw           jsonb,
    ai_status        varchar(12)  NOT NULL DEFAULT 'pending',
    ai_error         text,
    ai_attempts      integer      NOT NULL DEFAULT 0,
    handling_status  varchar(12)  NOT NULL DEFAULT 'open',
    handling_note    text,
    created_by       varchar(100) NOT NULL DEFAULT '',
    updated_by       varchar(100),
    created_at       timestamptz  NOT NULL DEFAULT now(),
    updated_at       timestamptz  NOT NULL DEFAULT now(),
    analyzed_at      timestamptz,
    CONSTRAINT complaints_pkey PRIMARY KEY (id),
    CONSTRAINT complaints_ai_status_check CHECK (ai_status IN ('pending', 'processing', 'analyzed', 'failed')),
    CONSTRAINT complaints_handling_status_check CHECK (handling_status IN ('open', 'in_progress', 'resolved', 'closed')),
    CONSTRAINT complaints_sentiment_check CHECK (sentiment IS NULL OR sentiment IN ('positive', 'neutral', 'negative')),
    CONSTRAINT complaints_priority_check CHECK (priority IS NULL OR priority IN ('low', 'medium', 'high', 'urgent'))
);
CREATE INDEX IF NOT EXISTS complaints_created_at_idx ON complaints (created_at DESC);
CREATE INDEX IF NOT EXISTS complaints_ai_status_idx ON complaints (ai_status);
CREATE INDEX IF NOT EXISTS complaints_priority_idx ON complaints (priority);

-- One row per event of the AI pipeline: each call to n8n (sent / error with
-- HTTP status and duration), each callback, and each rejected AI output.
CREATE TABLE IF NOT EXISTS complaint_ai_logs (
    id           bigint GENERATED BY DEFAULT AS IDENTITY,
    complaint_id bigint      NOT NULL,
    attempt      integer     NOT NULL DEFAULT 0,
    event        varchar(20) NOT NULL,
    http_status  integer,
    message      text,
    duration_ms  integer,
    created_at   timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT complaint_ai_logs_pkey PRIMARY KEY (id),
    CONSTRAINT fk_complaint_ai_logs_complaint FOREIGN KEY (complaint_id) REFERENCES complaints (id) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS complaint_ai_logs_complaint_idx ON complaint_ai_logs (complaint_id, id);
