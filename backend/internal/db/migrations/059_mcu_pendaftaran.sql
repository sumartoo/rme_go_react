-- MCU > Pendaftaran: what the registration form needs besides trxmcuheader and
-- trxmcudetail (057_mcu_hasil.sql). Same columns, types and primary keys as in
-- the legacy "lab" database; the transactions are loaded with
-- scripts/import-lab-mcu.sh.
--
--   refmcukategori  MCU Kategori (Umum, Perusahaan): trxmcuheader.mcukategoriid
--   refmcuinfo      where the patient heard of the clinic: trxmcuheader.mcuinfoid
--   trxmcunonlab    non-lab services of a registration (refnonlab), with the price charged
--   trxmcudoctor    doctors of a registration (refdoctor.doctorcode), with their fee %
-- No foreign keys, like the other re-imported tables.
CREATE TABLE IF NOT EXISTS refmcukategori (
    id          integer NOT NULL,
    mcukategori varchar(30),
    CONSTRAINT refmcukategori_pkey PRIMARY KEY (id)
);
INSERT INTO refmcukategori (id, mcukategori) VALUES (1, 'Umum'), (2, 'Perusahaan') ON CONFLICT (id) DO NOTHING;

CREATE TABLE IF NOT EXISTS refmcuinfo (
    id      integer NOT NULL,
    mcuinfo varchar(50),
    CONSTRAINT refmcuinfo_pkey PRIMARY KEY (id)
);
INSERT INTO refmcuinfo (id, mcuinfo) VALUES
    (1, 'google'), (2, 'google maps'), (3, 'instagram'), (4, 'tiktok'), (5, 'facebook'),
    (6, 'tlp klinik'), (7, 'rekomendasi saudara/teman'), (8, 'website klinik')
ON CONFLICT (id) DO NOTHING;

CREATE TABLE IF NOT EXISTS trxmcunonlab (
    id       integer GENERATED BY DEFAULT AS IDENTITY,
    headerid integer,
    nonlabid integer,
    price    double precision,
    CONSTRAINT trxmcunonlab_pkey PRIMARY KEY (id)
);
CREATE INDEX IF NOT EXISTS trxmcunonlab_headerid_idx ON trxmcunonlab (headerid);

CREATE TABLE IF NOT EXISTS trxmcudoctor (
    id            integer GENERATED BY DEFAULT AS IDENTITY,
    headerid      integer,
    doctor        varchar(20),
    feepercentage double precision,
    CONSTRAINT trxmcudoctor_pkey PRIMARY KEY (id)
);
CREATE INDEX IF NOT EXISTS trxmcudoctor_headerid_idx ON trxmcudoctor (headerid);
