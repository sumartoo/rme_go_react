-- Master Data > Pasien: the MCU patients (refpasien), separate from the clinic
-- patients in refmpasien. Same columns, types and primary key as in the legacy
-- "lab" database. Data is loaded with scripts/import-lab-pasien-mcu.sh.
-- rm (No RM) is YYMMDD of registration plus a 4-digit sequence; it is not
-- unique in lab (13 numbers appear twice), so there is no unique constraint.
-- companycode points to refcompany.companycode (not enforced, like lab).
CREATE TABLE IF NOT EXISTS refpasien (
    pasienid     integer GENERATED BY DEFAULT AS IDENTITY,
    pasienname   varchar(100),
    companycode  varchar(20),
    nik          varchar(20),
    departmen    varchar(50),
    position     varchar(50),
    rm           varchar(12) NOT NULL,
    address      varchar(200),
    gender       varchar(20),
    hp           varchar(15),
    telp         varchar(15),
    mail         varchar(50),
    birthdaydate timestamp(3) without time zone,
    isdeleted    boolean,
    createdby    varchar(50),
    createddate  timestamp(3) without time zone,
    modifyby     varchar(50),
    modifydate   timestamp(3) without time zone,
    deletedby    varchar(50),
    deleteddate  timestamp(3) without time zone,
    CONSTRAINT pk_pasien PRIMARY KEY (pasienid)
);

CREATE EXTENSION IF NOT EXISTS pg_trgm;
CREATE INDEX IF NOT EXISTS refpasien_rm ON refpasien (rm);
CREATE INDEX IF NOT EXISTS refpasien_pasienname_trgm ON refpasien USING gin (pasienname gin_trgm_ops);
