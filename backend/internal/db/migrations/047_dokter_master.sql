-- Master Data > Dokter Master: the kinds of MCU doctor (DOKTER UMUM,
-- CARDIOLOGIST, ...). Same columns, types and primary key as refdoctormaster
-- in the legacy "lab" database. Data is loaded with
-- scripts/import-lab-dokter-master.sh. Separate from the clinic doctors (refdokter).
CREATE TABLE IF NOT EXISTS refdoctormaster (
    doctormaster     integer GENERATED BY DEFAULT AS IDENTITY,
    doctormastername varchar(50),
    CONSTRAINT refdoctormaster_pkey PRIMARY KEY (doctormaster)
);
