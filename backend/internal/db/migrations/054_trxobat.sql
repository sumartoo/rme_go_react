-- Stok Farmasi > Stok Trace: a log line per stock movement of a drug at a
-- branch, written with every change of trxstock.stok. Same columns as trxobat
-- in the legacy "lab" database (quantities are double precision here, like
-- trxstock). Old lines come from scripts/import-lab-trxobat.sh.
--   laststock, stock  trxstock.stok before and after the movement
--   inout             'In' or 'Out'; byk is always positive
--   systemstock       = stock (kept for the legacy layout)
--   table_ref, id_ref the line that moved the stock:
--     TrxJualObat        trxjualobat.id   (sale; remarks "Transaksi <no_kwi>")
--     TrxFakturObat      trxfakturobat.id (goods receipt; "Good Receive <cabang>")
--     TrxStokAdjus       trxstokadjus.id  (stock adjustment; its keterangan)
--     TrxStokAdjusCancel trxstokadjus.id  (cancelled sale; "Cancel Transaksi <no_kwi>")
--     TrxJualObatDokter  legacy only (doctor's pending prescriptions)
CREATE TABLE IF NOT EXISTS trxobat (
    id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_obat     integer,
    cabang      varchar(5),
    laststock   double precision,
    inout       varchar(5),
    byk         double precision,
    stock       double precision,
    systemstock double precision,
    id_ref      integer,
    table_ref   varchar(50),
    remarks     varchar(300),
    createdby   varchar(20),
    createddate timestamp(3) NOT NULL DEFAULT LOCALTIMESTAMP
);

ALTER TABLE trxobat
    ADD CONSTRAINT fk_trxobat_obat   FOREIGN KEY (id_obat) REFERENCES refobat (id) ON DELETE CASCADE,
    ADD CONSTRAINT fk_trxobat_cabang FOREIGN KEY (cabang)  REFERENCES refbranch (kode);
CREATE INDEX IF NOT EXISTS trxobat_cabang_date_idx ON trxobat (cabang, createddate);
CREATE INDEX IF NOT EXISTS trxobat_obat_cabang_date_idx ON trxobat (id_obat, cabang, createddate);
