-- Master Data > Lab: the lab examinations (SGOT, SGPT, ...), each under a Lab
-- Sub Master (reflabsubmaster). Same columns, types and primary key as reflab
-- in the legacy "lab" database. Data is loaded with scripts/import-lab-lab.sh.
-- Here isdeleted is the Status: true = Non Active (183 of 593 rows in lab);
-- those rows are still listed. labsubmasterid points to reflabsubmaster (not
-- enforced, like lab). fee defaults to 15, like lab.
CREATE TABLE IF NOT EXISTS reflab (
    labid          integer GENERATED BY DEFAULT AS IDENTITY,
    labsubmasterid integer,
    labcode        varchar(50),
    labname        varchar(50),
    isdeleted      boolean,
    createddate    timestamp(3) without time zone,
    createby       varchar(30),
    modifieddate   timestamp(3) without time zone,
    modifiedby     varchar(30),
    deleteddate    timestamp(3) without time zone,
    deletedby      varchar(30),
    price          double precision,
    fee            double precision DEFAULT 15,
    CONSTRAINT pk_reflab PRIMARY KEY (labid)
);

CREATE INDEX IF NOT EXISTS reflab_labsubmasterid ON reflab (labsubmasterid);
