-- Transaksi Klinik > Pemeriksaan Dokter: the drugs the doctor prescribes and
-- the diagnoses the doctor records per registration, before (and apart from)
-- the sale. Same columns, types and primary keys as in the legacy "lab"
-- database; loaded with scripts/import-lab-pemeriksaan-dokter.sh.
--
-- No foreign keys to trxpendaftaran, refobat or reficd, because the Pendaftaran
-- and master re-imports truncate those tables with CASCADE.
--   id_kun   trxpendaftaran
--   id_obat  refobat; byk = quantity in the sale unit; dosis free text ("3x1")
--   icd_id   reficd
CREATE TABLE IF NOT EXISTS trxjualobatdokter (
    id      integer GENERATED BY DEFAULT AS IDENTITY,
    id_kun  integer,
    id_obat integer,
    byk     double precision,
    dosis   varchar(100),
    CONSTRAINT trxjualobatdokter_pkey PRIMARY KEY (id)
);
CREATE INDEX IF NOT EXISTS trxjualobatdokter_id_kun_idx ON trxjualobatdokter (id_kun);

CREATE TABLE IF NOT EXISTS trxjualdiagnosadokter (
    id     integer GENERATED BY DEFAULT AS IDENTITY,
    id_kun integer,
    icd_id integer,
    CONSTRAINT trxjualdiagnosadokter_pkey PRIMARY KEY (id)
);
CREATE INDEX IF NOT EXISTS trxjualdiagnosadokter_id_kun_idx ON trxjualdiagnosadokter (id_kun);
